SELECT
TO_CHAR(TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS') TIMESTAMP,
ID,
LPAD(' ', DEPTH) || OPERATION || ' ' || OPTIONS ||
DECODE(OBJECT_NAME, NULL, NULL, ' (' || OBJECT_NAME || ')')
Operation,
COST,
CARDINALITY
FROM
DBA_HIST_SQL_PLAN
WHERE
SQL_ID = '&HST_SQL_ID'
ORDER BY
1 DESC, 2;
