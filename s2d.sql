SELECT
COUNT(*) * 10 "ESTIMATED_SECONDS",
ASH.SQL_ID,
TO_CHAR(S.SQL_TEXT) SQL_TEXT
FROM
DBA_HIST_ACTIVE_SESS_HISTORY ASH,
DBA_HIST_SQLTEXT S
WHERE
ASH.SQL_ID = S.SQL_ID (+) AND
ASH.SESSION_ID = 1134 AND
ASH.SAMPLE_TIME BETWEEN
TO_TIMESTAMP('&start_time', 'YYYY-MM-DD HH24:MI:SS') AND
TO_TIMESTAMP('&end_time', 'YYYY-MM-DD HH24:MI:SS')
GROUP BY
ASH.SQL_ID,
TO_CHAR(S.SQL_TEXT)
ORDER BY
COUNT(*) DESC;


