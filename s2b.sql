SELECT
TO_CHAR(ASH.SAMPLE_TIME, 'YYYY-MM-DD HH24:MI:SS')
SAMPLE_TIME,
ASH.SESSION_ID,
ASH.BLOCKING_SESSION,
O.OBJECT_NAME,
S.SQL_TEXT
FROM
DBA_HIST_ACTIVE_SESS_HISTORY ASH,
DBA_HIST_SQLTEXT S,
DBA_OBJECTS O
WHERE
ASH.SQL_ID = S.SQL_ID (+) AND
ASH.CURRENT_OBJ# = O.OBJECT_ID (+) AND
ASH.EVENT like '&even_name' AND
ASH.SAMPLE_TIME BETWEEN
TO_TIMESTAMP('&start_time', 'YYYY-MM-DD HH24:MI:SS') AND
TO_TIMESTAMP('&end_time', 'YYYY-MM-DD HH24:MI:SS') AND
ASH.SESSION_STATE = 'WAITING'
ORDER BY
SAMPLE_TIME DESC;

