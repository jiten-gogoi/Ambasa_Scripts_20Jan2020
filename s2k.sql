SELECT
TO_CHAR(ASH.SAMPLE_TIME, 'YYYY-MM-DD HH24:MI:SS')
SAMPLE_TIME,
ASH.SESSION_ID,
ASH.TIME_WAITED,
O.OBJECT_NAME
FROM
DBA_HIST_ACTIVE_SESS_HISTORY ASH,
DBA_HIST_SQLTEXT S,
DBA_OBJECTS O
WHERE
ASH.SQL_ID = S.SQL_ID (+) AND
ASH.CURRENT_OBJ# = O.OBJECT_ID (+) AND
ASH.EVENT like 'db file sequential read' AND
ASH.SESSION_STATE = 'WAITING' and ash.time_waited > 1000000
ORDER BY
SAMPLE_TIME DESC;

