SELECT
EVENT,
WAIT_TIME_MILLI UPPER_WAIT_TIME_MS,
WAIT_COUNT,
WAIT_TIME_MILLI * DECODE(WAIT_TIME_MILLI, 1, 0.5, 0.75) *
WAIT_COUNT TIME_WAITED,
ROUND(RATIO_TO_REPORT(WAIT_TIME_MILLI *
DECODE(WAIT_TIME_MILLI, 1, 0.5, 0.75) * WAIT_COUNT) OVER () * 100)
PERCENT
FROM
V$EVENT_HISTOGRAM
WHERE
EVENT = 'db file sequential read'
ORDER BY
WAIT_TIME_MILLI;

